/**
 * Sending Domain Service — Email Marketing Module
 *
 * Gmail-only (M3 amendment, 2026-10-21): sending domains are verified with
 * DIRECT DNS lookups (SPF TXT, DKIM selectors, DMARC TXT). No Resend Domains
 * API, no Resend key, no Resend webhooks. Tenant isolation: all queries and
 * actions strictly scoped by workspaceId.
 *
 * How verification works:
 * - createSendingDomain stores the domain as PENDING plus the DNS records
 *   the owner must add (SPF + DMARC concrete; DKIM as the Google Workspace
 *   selector with a placeholder for the key from Google Admin — the key
 *   itself is generated by Google, never invented here).
 * - verifySendingDomain runs live DNS lookups and sets VERIFIED (SPF + DKIM
 *   present) or FAILED (domain resolves but records are missing). A DNS
 *   lookup that errors inconclusively (timeout, SERVFAIL) never downgrades
 *   an existing status — it leaves the row untouched.
 * - checkDomainDns is the shared lookup used by Phase 8 automated checks
 *   (send-orchestration). It accepts an injectable resolver so tests can
 *   run without network.
 *
 * RFC 2606 reserved domains (.example, .test, .localhost, .invalid) have no
 * real DNS by definition; Phase 8 checks fall back to the sending-domain
 * record for those (see domainAuthFor). Real domains always use live DNS.
 */

import { promises as dnsPromises } from 'node:dns';
import { db } from '../../../infrastructure/database/client.js';
import { SendingDomainStatus } from '@prisma/client';

export const DKIM_SELECTORS = ['google', 'default', 'selector1', 'selector2', 'mail', 'k1', 'dkim'];

export interface DnsRecordCheck {
  record: 'SPF' | 'DKIM' | 'DMARC';
  status: 'verified' | 'missing';
  selector?: string;
}

export interface DomainDnsResult {
  domain: string;
  spf: boolean;
  dkim: boolean;
  dkimSelector: string | null;
  dmarc: boolean;
  /** True when every lookup errored inconclusively (timeout/SERVFAIL) — the caller must not treat this as "missing". */
  inconclusive: boolean;
  note: string;
  records: DnsRecordCheck[];
}

export interface DnsResolver {
  resolveTxt(hostname: string): Promise<string[][]>;
}

const defaultResolver: DnsResolver = {
  resolveTxt: (hostname: string) => dnsPromises.resolveTxt(hostname),
};

/** Joins node:dns TXT chunks (each record is an array of strings). */
export function joinTxtRecords(records: string[][]): string[] {
  return records.map((parts) => parts.join(''));
}

function isConclusiveDnsError(err: unknown): boolean {
  const code = (err as { code?: string } | null)?.code;
  // NXDOMAIN / NODATA mean the name (or record type) definitively does not
  // exist — that is conclusive absence, not an inconclusive lookup.
  return code === 'ENOTFOUND' || code === 'ENODATA';
}

export function isReservedDomain(domain: string): boolean {
  const d = domain.trim().toLowerCase();
  return (
    d.endsWith('.example') ||
    d.endsWith('.test') ||
    d.endsWith('.localhost') ||
    d.endsWith('.invalid') ||
    d === 'example' ||
    d === 'test' ||
    d === 'localhost' ||
    d === 'invalid'
  );
}

/**
 * Live DNS check for one domain. SPF = a TXT record starting with v=spf1.
 * DKIM = a TXT record starting with v=DKIM1 under <selector>._domainkey.
 * DMARC = a TXT record starting with v=DMARC1 under _dmarc.
 */
export async function checkDomainDns(
  domain: string,
  resolver: DnsResolver = defaultResolver,
): Promise<DomainDnsResult> {
  const clean = domain.trim().toLowerCase();
  let spf = false;
  let dkim = false;
  let dkimSelector: string | null = null;
  let dmarc = false;
  let sawAnyData = false;
  let sawAnyInconclusive = false;

  const txt = async (host: string): Promise<string[] | null> => {
    try {
      const recs = await resolver.resolveTxt(host);
      sawAnyData = true;
      return joinTxtRecords(recs);
    } catch (err) {
      if (!isConclusiveDnsError(err)) sawAnyInconclusive = true;
      return null;
    }
  };

  const spfRecs = await txt(clean);
  if (spfRecs?.some((r) => r.trim().toLowerCase().startsWith('v=spf1'))) spf = true;

  for (const sel of DKIM_SELECTORS) {
    const recs = await txt(`${sel}._domainkey.${clean}`);
    if (recs?.some((r) => r.trim().toLowerCase().startsWith('v=dkim1'))) {
      dkim = true;
      dkimSelector = sel;
      break;
    }
  }

  const dmarcRecs = await txt(`_dmarc.${clean}`);
  if (dmarcRecs?.some((r) => r.trim().toLowerCase().startsWith('v=dmarc1'))) dmarc = true;

  const inconclusive = !sawAnyData && sawAnyInconclusive;
  const parts: string[] = [];
  parts.push(spf ? 'SPF record found.' : 'SPF record missing.');
  parts.push(dkim ? `DKIM record found (selector ${dkimSelector}).` : 'DKIM record missing (checked common selectors).');
  parts.push(dmarc ? 'DMARC record found.' : 'DMARC record missing.');
  if (inconclusive) parts.push('Live DNS lookup was inconclusive.');
  return {
    domain: clean,
    spf,
    dkim,
    dkimSelector,
    dmarc,
    inconclusive,
    note: parts.join(' '),
    records: [
      { record: 'SPF', status: spf ? 'verified' : 'missing' },
      { record: 'DKIM', status: dkim ? 'verified' : 'missing', selector: dkimSelector || undefined },
      { record: 'DMARC', status: dmarc ? 'verified' : 'missing' },
    ],
  };
}

/** DNS records the owner must add (guidance stored on the row at creation). */
export function guidanceRecords(domain: string): Array<Record<string, string>> {
  const clean = domain.trim().toLowerCase();
  return [
    { record: 'SPF', type: 'TXT', host: '@', value: 'v=spf1 include:_spf.google.com ~all', note: 'Gmail-only sending: authorize Google to send for this domain.' },
    { record: 'DKIM', type: 'TXT', host: `google._domainkey.${clean}`, value: 'v=DKIM1; k=rsa; p=PASTE_THE_PUBLIC_KEY_FROM_GOOGLE_ADMIN', note: 'Generate the DKIM key in Google Admin → Apps → Gmail → Authenticate email, then paste its public key here.' },
    { record: 'DMARC', type: 'TXT', host: `_dmarc.${clean}`, value: `v=DMARC1; p=none; rua=mailto:dmarc@${clean}`, note: 'Start with p=none (report only); tighten to quarantine/reject once SPF + DKIM pass.' },
  ];
}

export async function createSendingDomain(
  workspaceId: string,
  domain: string,
  region?: string,
) {
  const cleanDomain = domain.trim().toLowerCase();
  // No provider domain id under Gmail-only; a local id marks the row as
  // locally managed (never a Resend id). The column name is vestigial.
  const localDomainId = `local_${Date.now()}`;
  return db.sendingDomain.create({
    data: {
      workspaceId,
      domain: cleanDomain,
      resendDomainId: localDomainId,
      status: SendingDomainStatus.PENDING,
      region: region || null,
      dnsRecords: guidanceRecords(cleanDomain) as never,
    },
  });
}

export async function getSendingDomains(workspaceId: string) {
  return db.sendingDomain.findMany({
    where: { workspaceId },
    orderBy: { createdAt: 'desc' },
  });
}

export async function verifySendingDomain(workspaceId: string, id: string, resolver?: DnsResolver) {
  const record = await db.sendingDomain.findFirst({
    where: { id, workspaceId },
  });

  if (!record) {
    throw new Error('Sending domain not found');
  }

  const result = await checkDomainDns(record.domain, resolver);
  if (result.inconclusive) {
    // Never downgrade on inconclusive DNS (transient failure). The row keeps
    // its current status; the caller can retry verification later.
    return record;
  }

  const newStatus =
    result.spf && result.dkim ? SendingDomainStatus.VERIFIED : SendingDomainStatus.FAILED;
  const verifiedAt = newStatus === SendingDomainStatus.VERIFIED ? new Date() : record.verifiedAt;

  return db.sendingDomain.update({
    where: { id },
    data: {
      status: newStatus,
      dnsRecords: result.records as never,
      verifiedAt,
    },
  });
}

export async function deleteSendingDomain(workspaceId: string, id: string) {
  const record = await db.sendingDomain.findFirst({
    where: { id, workspaceId },
  });

  if (!record) {
    throw new Error('Sending domain not found');
  }

  // Gmail-only: nothing to remove at any provider — just delete the row.
  return db.sendingDomain.deleteMany({
    where: { id, workspaceId },
  });
}
